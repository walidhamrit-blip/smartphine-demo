export type DictKey = keyof typeof dict;

export function tr(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const entry = dict[key];
  let value: string = entry ? entry[lang] : key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function pick(lang: Lang, value: { en: string; ar: string } | undefined | null): string {
  if (!value) return "";
  return lang === "ar" ? value.ar || value.en : value.en || value.ar;
}

export function isRtl(lang: Lang): boolean {
  return lang === "ar";
}
